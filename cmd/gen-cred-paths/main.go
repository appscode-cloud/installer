package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"go.bytebuilders.dev/installer/apis/installer/v1alpha1"

	"sigs.k8s.io/yaml"
)

type define struct {
	name  string
	paths any
}

func main() {
	files := map[string][]define{
		"charts/ace-installer/templates/_cred_paths.tpl": {
			{"ace-installer.aceCredPaths", v1alpha1.ACECredPaths},
			{"ace-installer.featureCred.credPaths", v1alpha1.FeatureCredPaths},
		},
		"charts/opscenter-features/templates/_cred_paths.tpl": {
			{"opscenter-features.credPaths", v1alpha1.FeatureCredPaths},
		},
	}
	for file, defines := range files {
		if err := write(file, defines); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func write(file string, defines []define) error {
	var buf bytes.Buffer
	buf.WriteString("{{/* Code generated by cmd/gen-cred-paths from apis/installer/v1alpha1/cred_paths.go. DO NOT EDIT. */}}\n")
	for _, d := range defines {
		data, err := yaml.Marshal(d.paths)
		if err != nil {
			return err
		}
		fmt.Fprintf(&buf, "\n{{- define %q -}}\n%s{{- end -}}\n", d.name, data)
	}
	return os.WriteFile(filepath.Clean(file), buf.Bytes(), 0o644)
}
